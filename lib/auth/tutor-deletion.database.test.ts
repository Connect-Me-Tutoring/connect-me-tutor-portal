import { PGlite } from "@electric-sql/pglite";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { afterEach, beforeEach, describe, expect, it } from "vitest";

const migration = readFileSync(
  resolve("supabase/migrations/20261022194521_tutor_onboarding_deletion_guard.sql"),
  "utf8",
);
const baseline = readFileSync(
  resolve("supabase/migrations/00000000000000_baseline_schema.sql"),
  "utf8",
);
// Execute the repository's actual table/enum/FK definitions in PostgreSQL WASM.
// Only pgvector's unrelated embedding column is omitted (not bundled in PGlite).
const enums = baseline.match(/CREATE TYPE [\s\S]*? AS ENUM \([\s\S]*?\);/g) ?? [];
const tables = (baseline.match(/CREATE TABLE IF NOT EXISTS [\s\S]*?\n\);/g) ?? []).map((sql) =>
  sql.replace(/    "subject_embed"[^\n]*\n/, ""),
);
const identities =
  baseline.match(/ALTER TABLE [^;]*ADD GENERATED BY DEFAULT AS IDENTITY[^;]*;/g) ?? [];
const keys = baseline.match(/ALTER TABLE ONLY [^;]*ADD CONSTRAINT [^;]*PRIMARY KEY[^;]*;/g) ?? [];
const foreignKeys =
  baseline.match(/ALTER TABLE ONLY [^;]*ADD CONSTRAINT [^;]*FOREIGN KEY[^;]*;/g) ?? [];
const statusMigration = readFileSync(
  resolve("supabase/migrations/20260926000000_profile_deactivation.sql"),
  "utf8",
);
const statusHistoryTable = statusMigration.match(
  /create table if not exists public.profile_status_changes[\s\S]*?\n\);/,
)?.[0];
const existingDeleteFunction = statusMigration.match(
  /create or replace function private.on_profile_delete\(\)[\s\S]*?\$\$;/,
)?.[0];
const existingDeleteTrigger = statusMigration.match(
  /create trigger on_profile_delete[\s\S]*?private.on_profile_delete\(\);/,
)?.[0];
const ticketsTable = readFileSync(
  resolve("supabase/migrations/20260930000000_create_tickets.sql"),
  "utf8",
).match(/create table if not exists public.tickets[\s\S]*?\n\);/)?.[0];
if (!statusHistoryTable || !existingDeleteFunction || !existingDeleteTrigger || !ticketsTable)
  throw new Error("Required schema fixtures were not found");
const adminId = "10000000-0000-4000-8000-000000000001";
const tutorUserId = "10000000-0000-4000-8000-000000000002";
const adminProfileId = "20000000-0000-4000-8000-000000000001";
const tutorId = "20000000-0000-4000-8000-000000000002";
const settingsId = "30000000-0000-4000-8000-000000000002";
const email = "new.tutor@example.com";
const reason =
  "First portal access fails after resending the invite and attempting password recovery.";
let db: PGlite;

async function prepare(
  overrides: {
    profileId?: string;
    email?: string;
    reason?: string;
    recovery?: boolean;
    firstAccess?: boolean;
  } = {},
) {
  const result = await db.query<{ id: string; status: string; failure: string | null }>(
    "select * from public.prepare_tutor_onboarding_deletion($1, $2, $3, $4, $5)",
    [
      overrides.profileId ?? tutorId,
      overrides.email ?? email,
      overrides.reason ?? reason,
      overrides.recovery ?? true,
      overrides.firstAccess ?? true,
    ],
  );
  return result.rows[0];
}
async function deleteAuthUser() {
  // This is the SQL boundary GoTrue uses, under its dedicated non-admin role.
  const actor = (
    await db.query<{ actor: string }>(
      "select current_setting('request.jwt.claim.sub', true) as actor",
    )
  ).rows[0].actor;
  await db.exec(
    "select set_config('request.jwt.claim.sub', '', false); set role supabase_auth_admin",
  );
  try {
    await db.query("delete from auth.users where id = $1", [tutorUserId]);
  } finally {
    await db.exec("reset role");
    await db.query("select set_config('request.jwt.claim.sub', $1, false)", [actor]);
  }
}
async function count(table: string) {
  return (await db.query<{ count: number }>(`select count(*)::int as count from ${table}`)).rows[0]
    .count;
}

beforeEach(async () => {
  db = new PGlite();
  await db.exec(`
    create role anon; create role authenticated; create role service_role bypassrls;
    create role supabase_auth_admin;
    create schema auth; create schema private; create schema storage;
    create table auth.users(id uuid primary key, email text unique, last_sign_in_at timestamptz);
    create table auth.identities(id uuid primary key default gen_random_uuid(), user_id uuid references auth.users on delete cascade);
    create table auth.sessions(id uuid primary key default gen_random_uuid(), user_id uuid references auth.users on delete cascade);
    grant usage on schema auth to supabase_auth_admin;
    grant select, delete on auth.users to supabase_auth_admin;
    create function auth.uid() returns uuid language sql stable as $$
      select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid;
    $$;
    ${enums.join("\n")}
    ${tables.join("\n")}
    ${identities.join("\n")}
    ${keys.join("\n")}
    ${foreignKeys.join("\n")}
    ${statusHistoryTable}
    ${existingDeleteFunction}
    ${existingDeleteTrigger}
    ${ticketsTable}
    create table storage.objects(id uuid primary key default gen_random_uuid(), owner_id text);
    create function private.is_admin() returns boolean language sql security definer as $$
      select exists (select 1 from public."Profiles" where user_id = auth.uid() and role = 'Admin');
    $$;
    grant usage on schema public, private, auth to authenticated;
    ${migration}
  `);
  await db.query("insert into auth.users (id, email) values ($1, 'admin@example.com'), ($2, $3)", [
    adminId,
    tutorUserId,
    email,
  ]);
  await db.query("insert into public.user_notification_settings(id) values ($1), ($2)", [
    "30000000-0000-4000-8000-000000000001",
    settingsId,
  ]);
  await db.query(
    `insert into public."Profiles" (id, first_name, last_name, role, user_id, settings_id, email)
    values ($1, 'Admin', 'One', 'Admin', $2, '30000000-0000-4000-8000-000000000001', 'admin@example.com'),
      ($3, 'New', 'Tutor', 'Tutor', $4, $5, $6)`,
    [adminProfileId, adminId, tutorId, tutorUserId, settingsId, email],
  );
  await db.query(
    "insert into public.user_settings(user_id, last_active_profile_id) values ($1, $2)",
    [tutorUserId, tutorId],
  );
  await db.query("select set_config('request.jwt.claim.sub', $1, false)", [adminId]);
}, 20000);
afterEach(async () => {
  await db.close();
});

describe("onboarding tutor deletion database guard", () => {
  it("deletes an untouched account, queue and auth sessions atomically, leaving a durable audit and allowing the original email again", async () => {
    await db.query(
      `insert into public.pairing_requests(type, user_id, status, priority, notes) values ('tutor', $1, 'pending', 1, 'Auto-enqueued on account creation')`,
      [tutorId],
    );
    await db.query('insert into public."User_Availabilities"(profile_id) values ($1)', [tutorId]);
    await db.query("insert into auth.sessions(user_id) values ($1)", [tutorUserId]);
    await db.query("insert into auth.identities(user_id) values ($1)", [tutorUserId]);
    const attempt = await prepare();
    expect(attempt.status).toBe("pending");
    await deleteAuthUser();
    expect(await count('public."Profiles"')).toBe(1);
    expect(await count("public.pairing_requests")).toBe(0);
    expect(await count('public."User_Availabilities"')).toBe(0);
    expect(await count("public.user_settings")).toBe(0);
    expect(await count("auth.sessions")).toBe(0);
    expect(await count("auth.identities")).toBe(0);
    expect(await count("public.user_notification_settings")).toBe(1);
    const statusHistory = await db.query<{ to_status: string; changed_by: string | null }>(
      "select to_status, changed_by from public.profile_status_changes",
    );
    expect(statusHistory.rows).toEqual([{ to_status: "Deleted", changed_by: null }]);
    const audit = await db.query("select * from public.tutor_deletion_audit where id = $1", [
      attempt.id,
    ]);
    expect(audit.rows[0]).toMatchObject({
      status: "succeeded",
      actor_id: adminId,
      profile_id: tutorId,
      reason,
      recovery_attempted: true,
      first_access_failure: true,
      email,
    });
    await db.query("insert into auth.users(id, email) values (gen_random_uuid(), $1)", [email]);
  });

  it.each([
    ["Sessions", 'insert into public."Sessions"(tutor_id, duration) values ($1, 1)'],
    ["Enrollments", 'insert into public."Enrollments"(tutor_id, duration) values ($1, 1)'],
    ["Events", 'insert into public."Events"(tutor_id, hours) values ($1, 2)'],
    ["Pairings", 'insert into public."Pairings"(tutor_id, student_id) values ($1, $1)'],
    ["pairing_matches", "insert into public.pairing_matches(tutor_id, student_id) values ($1, $1)"],
    [
      "messages",
      "insert into public.messages(user_id, room_id, content) values ($1, gen_random_uuid(), 'Already tutoring')",
    ],
    ["Forms", 'insert into public."Forms"(submitter) values ($1)'],
    ["Notifications", 'insert into public."Notifications"(tutor_id) values ($1)'],
    [
      "JSON history",
      "insert into public.\"Requests\"(request_information) values (jsonb_build_object('tutor', $1::text))",
    ],
  ])("blocks %s history and retains all records", async (_, sql) => {
    await db.query(sql, [tutorId]);
    expect((await prepare()).status).toBe("blocked");
    await expect(deleteAuthUser()).rejects.toThrow("confirmation is required");
    expect(await count('public."Profiles"')).toBe(2);
    expect(await count("auth.users")).toBe(2);
  });

  it.each(["tutoring_hours = 1", "orientation_completed_at = now()"])(
    "protects profile activity: %s",
    async (assignment) => {
      await db.query(`update public."Profiles" set ${assignment} where id = $1`, [tutorId]);
      expect((await prepare()).status).toBe("blocked");
    },
  );
  it("protects previous status changes and support activity", async () => {
    await db.query(
      "insert into public.profile_status_changes(profile_id, to_status) values ($1, 'Inactive')",
      [tutorId],
    );
    expect((await prepare()).status).toBe("blocked");
  });
  it("protects auth-linked tickets even without a profile association", async () => {
    await db.query(
      "insert into public.tickets(user_id, category, subject, description) values ($1, 'hours', 'Existing tutoring hours', 'Tutor has a history of activity')",
      [tutorUserId],
    );
    expect((await prepare()).status).toBe("blocked");
  });
  it("protects another profile's array association", async () => {
    await db.query('update public."Profiles" set tutor_ids = array[$1::uuid] where id = $2', [
      tutorId,
      adminProfileId,
    ]);
    expect((await prepare()).status).toBe("blocked");
  });
  it("protects shared authentication accounts", async () => {
    await db.query(
      "insert into public.\"Profiles\" (first_name, last_name, user_id, role, settings_id) values ('Other', 'Profile', $1, 'Student', $2)",
      [tutorUserId, settingsId],
    );
    expect((await prepare()).failure).toContain("shared");
  });
  it("protects duplicate-email profiles on different auth accounts", async () => {
    await db.query('update public."Profiles" set email = $1 where id = $2', [
      email,
      adminProfileId,
    ]);
    expect((await prepare()).failure).toContain("shared");
  });
  it.each([
    "status = 'accepted'",
    "in_queue = false",
    "notes = 'Manually paired'",
    "priority = 2",
    "notes = null",
  ])("protects changed onboarding queues: %s", async (assignment) => {
    await db.query(
      `insert into public.pairing_requests(type, user_id, priority, notes) values ('tutor', $1, 1, 'Auto-enqueued on account creation')`,
      [tutorId],
    );
    await db.exec(`update public.pairing_requests set ${assignment}`);
    expect((await prepare()).status).toBe("blocked");
  });
  it("blocks legacy matches referring to the auth UUID", async () => {
    await db.query("insert into public.pairing_matches(tutor_id, student_id) values ($1, $2)", [
      tutorUserId,
      tutorId,
    ]);
    expect((await prepare()).status).toBe("blocked");
  });
  it("blocks attendance associated only by email", async () => {
    await db.query(
      "insert into public.zoom_participant_events(participant_id, name, email, action, session_id) values ('zoom-id', 'Tutor', $1, 'join', null)",
      [email],
    );
    expect((await prepare()).status).toBe("blocked");
  });
  it("blocks storage ownership", async () => {
    await db.query("insert into storage.objects(owner_id) values ($1)", [tutorUserId]);
    expect((await prepare()).status).toBe("blocked");
  });
  it("blocks unknown future cascade tables", async () => {
    await db.exec(
      'create table public.future_history(profile_id uuid references public."Profiles" on delete cascade)',
    );
    await db.query("insert into public.future_history values ($1)", [tutorId]);
    expect((await prepare()).status).toBe("blocked");
  });
  it.each([null, tutorUserId])("rejects unauthenticated/non-admin caller %s", async (actor) => {
    await db.query("select set_config('request.jwt.claim.sub', $1, false)", [actor ?? ""]);
    await db.exec("set role authenticated");
    await expect(prepare()).rejects.toThrow("Admin access required");
    await db.exec("reset role");
    expect(await count("public.tutor_deletion_audit")).toBe(0);
  });
  it("prevents forged audits and private helper calls from authenticated clients", async () => {
    await db.exec("set role authenticated");
    await expect(
      db.exec("update public.tutor_deletion_audit set status = 'succeeded'"),
    ).rejects.toThrow("permission denied");
    await expect(
      db.query("select private.tutor_deletion_blocker($1, $2)", [tutorId, email]),
    ).rejects.toThrow("permission denied");
    await db.exec("reset role");
  });
  it("rejects non-Tutors and mismatched email confirmations", async () => {
    expect((await prepare({ profileId: adminProfileId, email: "admin@example.com" })).status).toBe(
      "blocked",
    );
    expect((await prepare({ email: "someone.else@example.com" })).status).toBe("blocked");
  });
  it.each([{ recovery: false }, { firstAccess: false }, { reason: "short" }])(
    "requires deliberate confirmations %j",
    async (input) => {
      await expect(prepare(input)).rejects.toThrow("Confirm first-access");
    },
  );
  it("revalidates history created after preparation", async () => {
    expect((await prepare()).status).toBe("pending");
    await db.query('insert into public."Sessions"(tutor_id, duration) values ($1, 1)', [tutorId]);
    await expect(deleteAuthUser()).rejects.toThrow("Sessions");
    expect(await count('public."Sessions"')).toBe(1);
    expect(await count("auth.users")).toBe(2);
  });
  it("revalidates shared accounts and changed targets after preparation", async () => {
    await prepare();
    await db.query(
      "insert into public.\"Profiles\" (first_name, last_name, user_id, role, settings_id) values ('New', 'Student', $1, 'Student', $2)",
      [tutorUserId, settingsId],
    );
    await expect(deleteAuthUser()).rejects.toThrow("shared");
  });
  it("expires stale requests and rechecks admin privileges", async () => {
    await prepare();
    await db.exec(
      "update public.tutor_deletion_audit set created_at = now() - interval '6 minutes'",
    );
    await expect(deleteAuthUser()).rejects.toThrow("confirmation is required");
    await prepare();
    await db.query("update public.\"Profiles\" set role = 'Student' where id = $1", [
      adminProfileId,
    ]);
    await expect(deleteAuthUser()).rejects.toThrow("no longer has admin access");
  });
  it("rolls back queue cleanup, profile cascades and success audit if deletion fails", async () => {
    await db.query(
      `insert into public.pairing_requests(type, user_id, priority, notes) values ('tutor', $1, 1, 'Auto-enqueued on account creation')`,
      [tutorId],
    );
    const attempt = await prepare();
    await db.exec(`create function public.simulate_failure() returns trigger language plpgsql as $$ begin raise exception 'Simulated cascade failure'; end; $$;
      create trigger zzz_failure after delete on auth.users for each row execute function public.simulate_failure();`);
    await expect(deleteAuthUser()).rejects.toThrow("Simulated cascade failure");
    expect(await count("auth.users")).toBe(2);
    expect(await count('public."Profiles"')).toBe(2);
    expect(await count("public.pairing_requests")).toBe(1);
    expect(await count("public.user_settings")).toBe(1);
    const audit = await db.query<{ status: string }>(
      "select status from public.tutor_deletion_audit where id = $1",
      [attempt.id],
    );
    expect(audit.rows[0].status).toBe("pending");
  });
  it("rejects null email via direct RPC", async () => {
    const result = await db.query<{ status: string }>(
      "select * from public.prepare_tutor_onboarding_deletion($1, null, $2, true, true)",
      [tutorId, reason],
    );
    expect(result.rows[0].status).toBe("blocked");
  });
  it("blocks missing auth linkage and differing auth email", async () => {
    await db.query("update auth.users set email = 'changed@example.com' where id = $1", [
      tutorUserId,
    ]);
    expect((await prepare()).status).toBe("blocked");
    await db.query('update public."Profiles" set user_id = null where id = $1', [tutorId]);
    expect((await prepare()).status).toBe("blocked");
  });
  it("protects shared settings", async () => {
    await db.query('update public."Profiles" set settings_id = $1 where id = $2', [
      settingsId,
      adminProfileId,
    ]);
    expect((await prepare()).failure).toContain("settings");
  });
  it("rejects anonymous execute and hides audits from non-admins", async () => {
    await prepare();
    await db.exec("set role anon");
    await expect(prepare()).rejects.toThrow("permission denied");
    await db.exec("reset role");
    await db.query("select set_config('request.jwt.claim.sub', $1, false)", [tutorUserId]);
    await db.exec("set role authenticated");
    expect(await count("public.tutor_deletion_audit")).toBe(0);
    await db.exec("reset role");
  });
  it("blocks changed profile linkage even if it becomes a non-Tutor after preparation", async () => {
    await prepare();
    await db.query("update public.\"Profiles\" set role = 'Student' where id = $1", [tutorId]);
    await expect(deleteAuthUser()).rejects.toThrow("selected tutor account changed");
    expect(await count("auth.users")).toBe(2);
  });
  it("blocks a stale prepared request after a role change and superseding rejection", async () => {
    await prepare();
    await db.query("update public.\"Profiles\" set role = 'Student' where id = $1", [tutorId]);
    expect((await prepare()).status).toBe("blocked");
    await expect(deleteAuthUser()).rejects.toThrow("confirmation is required");
    expect(await count("auth.users")).toBe(2);
  });
  it("rolls back deletion if a trigger suppresses the profile cascade", async () => {
    await prepare();
    await db.exec(`create function public.suppress_delete() returns trigger language plpgsql as $$ begin return null; end; $$;
      create trigger suppress_delete before delete on public."Profiles" for each row execute function public.suppress_delete();`);
    await expect(deleteAuthUser()).rejects.toThrow("profile removal did not complete");
    expect(await count("auth.users")).toBe(2);
    expect(await count('public."Profiles"')).toBe(2);
  });
});
